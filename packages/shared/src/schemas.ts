import { z } from 'zod';

export const IngestRequestSchema = z.object({
  url: z.string().url({ message: 'URL không hợp lệ' }),
  kind: z.enum(['video', 'article', 'auto']).default('auto'),
  targetLang: z.string().default('vi'),
  // Optional pre-fetched captions from Chrome Extension (Tier 1a)
  extensionCaptions: z
    .array(
      z.object({
        i: z.number(),
        start: z.number(),
        end: z.number(),
        text: z.string(),
      })
    )
    .optional(),
  videoTitle: z.string().optional(),
  thumbnailUrl: z.string().optional(),
});

export type IngestRequest = z.infer<typeof IngestRequestSchema>;

export const UpdateProgressSchema = z.object({
  mediaId: z.string().uuid(),
  lastPositionSec: z.number().min(0),
  lastSegmentIdx: z.number().int().min(0),
  percentComplete: z.number().min(0).max(100),
  status: z.enum(['new', 'in_progress', 'done']).default('in_progress'),
});

export type UpdateProgressRequest = z.infer<typeof UpdateProgressSchema>;

export const DictationCheckSchema = z.object({
  targetText: z.string(),
  userInput: z.string(),
});

export type DictationCheckRequest = z.infer<typeof DictationCheckSchema>;

export const SaveVocabSchema = z.object({
  term: z.string().min(1),
  translation: z.string().min(1),
  context: z.string().optional(),
  mediaId: z.string().uuid().optional(),
  segmentIdx: z.number().int().optional(),
});

export type SaveVocabRequest = z.infer<typeof SaveVocabSchema>;

// Schema for TOEIC/IELTS questions generated by LLM
export const ExamItemSchema = z.object({
  orderNo: z.number(),
  itemType: z.string(), // e.g. 'part5_mcq', 'part7_comprehension', 'ielts_tfng'
  question: z.string(),
  options: z.array(z.string()).optional(), // For MCQ: 4 options [A, B, C, D]
  answer: z.union([z.string(), z.array(z.string())]),
  explanation: z.string(), // Vietnamese explanation
  evidence: z
    .object({
      text: z.string().optional(),
      start: z.number().optional(),
      end: z.number().optional(),
      paragraphIdx: z.number().optional(),
    })
    .optional(),
});

export const ExamPackageSchema = z.object({
  title: z.string(),
  type: z.enum([
    'dictation',
    'fill_blank',
    'toeic_listening',
    'toeic_reading',
    'ielts_listening',
    'ielts_reading',
  ]),
  level: z.string().optional(),
  instructions: z.string(),
  timeLimitSec: z.number().optional(),
  items: z.array(ExamItemSchema),
});

export type ExamPackage = z.infer<typeof ExamPackageSchema>;
export type ExamItem = z.infer<typeof ExamItemSchema>;
